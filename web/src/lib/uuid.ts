/**
 * A random v4 UUID. `crypto.randomUUID` exists only in secure contexts (HTTPS, `localhost`,
 * `127.0.0.1`), so a UI opened by LAN IP falls back to `crypto.getRandomValues`, which works
 * everywhere.
 */
export function randomUuid(source: Crypto = crypto): string {
  if (typeof source.randomUUID === 'function') return source.randomUUID();
  const bytes = source.getRandomValues(new Uint8Array(16));
  bytes[6] = ((bytes[6] ?? 0) & 0x0f) | 0x40; // version 4
  bytes[8] = ((bytes[8] ?? 0) & 0x3f) | 0x80; // variant 10xx
  const hex = Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
